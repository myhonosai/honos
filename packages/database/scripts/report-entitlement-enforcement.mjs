import pg from 'pg';
import { writeFile } from 'node:fs/promises';
// B6 foundation: inventory of how every runtime-callable HON database function is gated by the organization's
// plan entitlement today. Read-only catalog analysis of a disposable localhost database with all migrations applied.
// It classifies each function by its own body and, transitively, by the helpers it calls:
//   STATUS_GATED  - checks organization_entitlements.status = 'ACTIVE' (a SUSPENDED entitlement is refused)
//   TIER_ONLY     - reads the entitlement tier but never its status (a SUSPENDED entitlement would still pass)
//   HQ_SCOPE      - HQ platform functions (HQ grants, never a school's entitlement)
//   PROVIDER_SCOPE- provider/integration entry points with no human subject
//   UNGATED       - no entitlement reference, directly or through helpers
// This is static analysis: it shows where enforcement exists, not that each path is correct. B6 must add a
// behavioural coverage proof before any payment-driven suspension can be relied on.
const url = new URL(process.env.DATABASE_URL ?? '');
if (url.hostname !== 'localhost' || url.port !== '5432' || !/^\/hon_[a-z_]+_validation$/.test(url.pathname)) throw new Error('Only a disposable localhost validation database.');
const runtime = process.env.HON_RUNTIME_ROLE ?? 'hon_champions_runtime';
if (!/^hon_[a-z_]+$/.test(runtime)) throw new Error('Unsafe runtime role name.');
const client = new pg.Client({ connectionString: url.toString(), ssl: false });
await client.connect();
try {
  const all = (await client.query(`SELECT p.oid, p.proname, p.oid::regprocedure::text sig, p.prosrc src, has_function_privilege($1, p.oid, 'EXECUTE') callable
    FROM pg_proc p WHERE p.pronamespace = 'hon'::regnamespace AND p.prokind = 'f' ORDER BY p.oid::regprocedure::text`, [runtime])).rows;
  const byName = new Map();
  for (const f of all) { if (!byName.has(f.proname)) byName.set(f.proname, []); byName.get(f.proname).push(f); }
  const names = [...byName.keys()].filter(n => n.length > 6);
  const calls = new Map(all.map(f => [f.oid, new Set(names.filter(n => n !== f.proname && new RegExp(`\\b${n}\\s*\\(`).test(f.src)))]));
  const own = f => {
    if (!/organization_entitlements/.test(f.src)) return null;
    return /status\s*(=|IN\s*\()\s*'ACTIVE'|status\s*<>\s*'ACTIVE'|\.status\s*=\s*'ACTIVE'/i.test(f.src) ? 'STATUS_GATED' : 'TIER_ONLY';
  };
  // Fixed point over helpers: STATUS_GATED dominates TIER_ONLY.
  const rank = { STATUS_GATED: 2, TIER_ONLY: 1 };
  const memo = new Map(all.map(f => [f.oid, { cls: own(f), via: null }]));
  for (let changed = true; changed;) {
    changed = false;
    for (const f of all) {
      const cur = memo.get(f.oid);
      for (const callee of calls.get(f.oid)) for (const g of byName.get(callee)) {
        const c = memo.get(g.oid);
        if (c.cls && (rank[c.cls] ?? 0) > (rank[cur.cls] ?? 0)) { cur.cls = c.cls; cur.via = cur.via && own(f) ? cur.via : callee; changed = true; }
      }
    }
  }
  // HQ authority: the function (or a helper it calls) resolves an HQ actor.
  const hqHelper = n => /^require_[a-z_]*hq[a-z_]*$/.test(n);
  const hq = new Map(all.map(f => [f.oid, hqHelper(f.proname)]));
  for (let changed = true; changed;) {
    changed = false;
    for (const f of all) if (!hq.get(f.oid) && [...calls.get(f.oid)].some(n => hqHelper(n) || byName.get(n).some(g => hq.get(g.oid)))) { hq.set(f.oid, true); changed = true; }
  }
  const entry = all.filter(f => f.callable && !/^guard_/.test(f.proname));
  const rows = entry.map(f => {
    const m = memo.get(f.oid);
    // An HQ command that resolves its HQ actor directly is HQ scope even when it also touches an entitlement.
    const cls = /(^|_)hq(_|$)|_from_hq$/.test(f.proname) || (hq.get(f.oid) && (!m.cls || [...calls.get(f.oid)].some(hqHelper))) ? 'HQ_SCOPE'
      : /^ingest_|_provider_event|^saas_payment_actor/.test(f.proname) ? 'PROVIDER_SCOPE' : (m.cls ?? 'UNGATED');
    return { function: f.sig, classification: cls, via: cls === m.cls ? m.via : null };
  }).sort((a, b) => a.classification.localeCompare(b.classification) || a.function.localeCompare(b.function));
  const counts = rows.reduce((t, r) => ({ ...t, [r.classification]: (t[r.classification] ?? 0) + 1 }), {});
  const report = { runtimeRole: runtime, runtimeCallable: rows.length, counts, functions: rows };
  if (process.argv[2] === '--markdown') {
    const out = process.argv[3];
    if (!out || !/^docs\/architecture\/[A-Z_]+\.md$/.test(out)) throw new Error('Usage: --markdown docs/architecture/<NAME>.md');
    const md = [`# HON entitlement enforcement inventory (generated)`, '',
      'Generated by `packages/database/scripts/report-entitlement-enforcement.mjs` from a disposable database with every migration applied.',
      `It lists every function the \`${runtime}\` role can execute, classified by whether it checks the organization's plan entitlement`,
      '(directly or through the helpers it calls). Static analysis only: B6 needs a behavioural coverage proof before payment-driven',
      'suspension is relied on. Regenerate after migrations change.', '',
      'Read with care: `UNGATED` includes small helpers and tenant-context (RLS) functions whose callers, or the API layer',
      '(`tierIncludesFeature` in `apps/api`), apply the entitlement check, and family-portal functions governed by family grants.',
      'B6 must decide, function by function, which of them a SUSPENDED or RESTRICTED school may still use. `STATUS_GATED` means the',
      'status is read; a function may report it instead of refusing (the B5.1 billing reads report it on purpose, so a lapsed school',
      'can still see its billing).', '',
      '| Classification | Meaning | Count |', '|---|---|---|',
      ...[['STATUS_GATED', "Checks `status = 'ACTIVE'`: a SUSPENDED entitlement is refused"],
        ['TIER_ONLY', 'Reads the tier but not the status: a SUSPENDED entitlement would still pass'],
        ['UNGATED', 'No entitlement reference (directly or through helpers)'],
        ['HQ_SCOPE', 'HQ platform functions, governed by HQ grants'],
        ['PROVIDER_SCOPE', 'Provider entry points with no human subject']].map(([c, m]) => `| ${c} | ${m} | ${counts[c] ?? 0} |`),
      '', '| Function | Classification | Through helper |', '|---|---|---|',
      ...rows.map(r => `| \`${r.function}\` | ${r.classification} | ${r.via ? `\`${r.via}\`` : ''} |`), ''].join('\n');
    await writeFile(new URL(`../../../${out}`, import.meta.url), md);
    console.log(`Wrote ${out}: ${rows.length} runtime-callable functions`, counts);
  } else console.log(JSON.stringify(report, null, 1));
} finally { await client.end(); }
