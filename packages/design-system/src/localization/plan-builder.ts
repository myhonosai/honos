function prefix<T extends Record<string, string>>(copy: T): { [K in keyof T as `planBuilder.${K & string}`]: T[K] } {
  return Object.fromEntries(Object.entries(copy).map(([k, v]) => ['planBuilder.' + k, v])) as never;
}
