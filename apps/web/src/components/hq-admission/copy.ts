export const ADMISSION_LANGUAGES = { en, ko, es } as const;
export type AdmissionLanguage = keyof typeof ADMISSION_LANGUAGES;
export function admissionCopy(language: string): (key: AdmissionCopyKey, values?: Record<string, string>) => string {
  const table = ADMISSION_LANGUAGES[(language in ADMISSION_LANGUAGES ? language : 'en') as AdmissionLanguage];
  return (key, values = {}) => table[key].replace(/\{(\w+)\}/g, (_, name: string) => values[name] ?? `{${name}}`);
}
