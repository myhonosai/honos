/** Labels only. Never infer entitlement or eligibility from an operational status. */
export function hqSchoolStatus(language: string, status: string): string {
  const key = status === 'ACTIVE' ? 'statusActive' : status === 'SUSPENDED' ? 'statusSuspended' : status === 'ARCHIVED' ? 'statusArchived' : 'statusUnavailable';
  return hqSchoolText(language, key);
}
