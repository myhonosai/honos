export type SchoolPlanKey = Key;
export function schoolPlanText(language: string, key: Key, vars: Record<string, string> = {}): string {
  const text = (language === 'ko' ? ko : language === 'es' ? es : en)[key];
  return text.replace(/\{(\w+)\}/g, (m, name: string) => vars[name] ?? m);
}
export function isSchoolPlanKey(key: string): key is Key { return Object.hasOwn(en, key); }
