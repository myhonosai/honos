export const MAKE_SHOP_LANGUAGES = { en, ko, es } as const;
export function makeShopText(language: string, key: MakeShopKey, vars: Record<string, string> = {}): string {
  const table = language === 'ko' ? ko : language === 'es' ? es : en;
  return table[key].replace(/\{(\w+)\}/g, (match, name: string) => vars[name] ?? match);
}
