export const STUDIO_LANGUAGES = { en, ko, es } as const;
export function studioText(language: string, key: StudioKey, vars: Record<string, string> = {}): string {
  const table = language === 'ko' ? ko : language === 'es' ? es : en;
  return table[key].replace(/\{(\w+)\}/g, (match, name: string) => vars[name] ?? match);
}
