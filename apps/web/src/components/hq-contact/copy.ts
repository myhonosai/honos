export type HqContactKey = Key;
export function hqContactText(language: string, key: Key, vars: Record<string, string> = {}): string {
  const text = (language === 'ko' ? ko : language === 'es' ? es : en)[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? '');
}
export function hqContactRefusalKey(code: string | null): Key {
  const key = `r_${code ?? ''}`;
  return (Object.hasOwn(en, key) ? key : 'r_OTHER') as Key;
}
