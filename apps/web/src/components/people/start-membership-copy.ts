export function startText(language: string, key: StartKey, vars: Readonly<Record<string, string | number>> = {}): string {
  const table = language.startsWith('ko') ? ko : language.startsWith('es') ? es : en;
  return Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), table[key]);
}
