const CATALOG: Record<HonLanguage, Record<HomeKey, string>> = { en, ko, es };

export function homeText(language: string, key: HomeKey, values: Record<string, string | number> = {}): string {
  const template = CATALOG[language as HonLanguage]?.[key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
}
